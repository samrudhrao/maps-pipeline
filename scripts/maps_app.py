def generate_pdf_report(sample_name, outdir, summary, qc, run_start_time):
    if not REPORTLAB_AVAILABLE:
        return None
    
    pdf_path = f"{outdir}/{sample_name}_clinical_report.pdf"
    doc = SimpleDocTemplate(pdf_path, pagesize=letter,
                            rightMargin=0.75*inch, leftMargin=0.75*inch,
                            topMargin=0.75*inch, bottomMargin=0.75*inch)
    
    styles = getSampleStyleSheet()
    bsw_blue = colors.HexColor('#003087')
    
    title_style = ParagraphStyle('Title', parent=styles['Title'],
                                  textColor=bsw_blue, fontSize=18, spaceAfter=6)
    h2_style = ParagraphStyle('H2', parent=styles['Heading2'],
                               textColor=bsw_blue, fontSize=13, spaceAfter=4)
    h3_style = ParagraphStyle('H3', parent=styles['Heading3'],
                               textColor=bsw_blue, fontSize=11, spaceAfter=3)
    normal = styles['Normal']
    small = ParagraphStyle('Small', parent=styles['Normal'], fontSize=9)
    
    story = []
    
    # Header
    story.append(Paragraph("MAPS Clinical Report", title_style))
    story.append(Paragraph("Metagenomic Abundance and Pathogen Scoring", styles['Normal']))
    story.append(Paragraph("Baylor Scott & White Health", styles['Normal']))
    story.append(HRFlowable(width="100%", thickness=2, color=bsw_blue))
    story.append(Spacer(1, 0.1*inch))
    
    # Run info
    story.append(Paragraph("Run Information", h2_style))
    run_data = [
        ["Sample Name", sample_name],
        ["Run Date", summary.get("timestamp", dt.now().strftime("%Y-%m-%d %H:%M"))],
        ["Run Started", run_start_time],
        ["Specimen Type", summary.get("infection_type", "N/A")],
        ["Generated By", f"MAPS Pipeline | User: {st.session_state.get('user_initials','N/A')}"],
    ]
    run_table = Table(run_data, colWidths=[2*inch, 4.5*inch])
    run_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (0,-1), colors.HexColor('#DCE6F1')),
        ('TEXTCOLOR', (0,0), (0,-1), bsw_blue),
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 10),
        ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
        ('ROWBACKGROUNDS', (0,0), (-1,-1), [colors.white, colors.HexColor('#F5F8FF')]),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(run_table)
    story.append(Spacer(1, 0.15*inch))
    
    # Clinical summary
    story.append(Paragraph("Clinical Summary", h2_style))
    story.append(Paragraph(summary.get("clinical_summary", "N/A"), normal))
    story.append(Spacer(1, 0.15*inch))
    
    # QC Report
    story.append(Paragraph("QC Report", h2_style))
    qc_status = qc.get("status", "UNKNOWN")
    status_color = colors.green if qc_status == "PASS" else colors.red
    story.append(Paragraph(f'<font color="{"green" if qc_status=="PASS" else "red"}">QC Status: {qc_status}</font>', normal))
    story.append(Spacer(1, 0.05*inch))
    
    qc_data = [["Metric", "Value", "Threshold", "Status"]]
    qc_checks = [
        ("Total Reads", f"{qc.get('total_reads',0):,}", "≥ 50,000", "✓" if qc.get('checks',{}).get('total_reads_ok', True) else "✗"),
        ("Human DNA", f"{qc.get('human_pct',0):.1f}%", "≤ 90%", "✓" if qc.get('checks',{}).get('human_pct_ok', True) else "✗"),
        ("Microbial Reads", f"{qc.get('microbial_reads',0):,}", "≥ 1,000", "✓" if qc.get('checks',{}).get('microbial_reads_ok', True) else "✗"),
        ("Q30 Rate", f"{qc.get('q30_rate',0):.1f}%", "≥ 50%", "✓" if qc.get('q30_rate',0) >= 50 else "✗"),
        ("Q20 Rate", f"{qc.get('q20_rate',0):.1f}%", "≥ 70%", "✓" if qc.get('q20_rate',0) >= 70 or qc.get('q20_rate',0) == 0 else "✗"),
        ("Duplication", f"{qc.get('duplication_pct',0):.1f}%", "≤ 80%", "✓" if qc.get('duplication_pct',0) <= 80 else "✗"),
        ("Insert Size", f"{qc.get('insert_size',0)}bp", "≥ 100bp", "✓" if qc.get('insert_size',0) == 0 or qc.get('insert_size',0) >= 100 else "✗"),
    ]
    qc_data.extend(qc_checks)
    qc_table = Table(qc_data, colWidths=[2*inch, 1.5*inch, 2*inch, 1*inch])
    qc_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), bsw_blue),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 9),
        ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F5F8FF')]),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 5),
    ]))
    story.append(qc_table)
    story.append(Spacer(1, 0.15*inch))
    
    # Detected pathogens
    abundance_path = f"{outdir}/{sample_name}_abundance.csv"
    if _os.path.exists(abundance_path):
        import pandas as _pd
        df = _pd.read_csv(abundance_path)
        df = df[df["relative_abundance_%"] >= 3.0].sort_values("relative_abundance_%", ascending=False)
        if len(df) > 0:
            story.append(Paragraph("Detected Pathogens (≥3% threshold)", h2_style))
            path_data = [["Rank", "Organism", "Abundance (%)"]]
            for i, (_, row) in enumerate(df.iterrows(), 1):
                path_data.append([str(i), row["organism"], f"{row['relative_abundance_%']:.2f}%"])
            path_table = Table(path_data, colWidths=[0.5*inch, 4.5*inch, 1.5*inch])
            path_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), bsw_blue),
                ('TEXTCOLOR', (0,0), (-1,0), colors.white),
                ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
                ('FONTSIZE', (0,0), (-1,-1), 9),
                ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
                ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F5F8FF')]),
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('PADDING', (0,0), (-1,-1), 5),
            ]))
            story.append(path_table)
            story.append(Spacer(1, 0.15*inch))
    
    # AI scores
    ai_path = f"{outdir}/{sample_name}_ai_scores.csv"
    if _os.path.exists(ai_path):
        ai_df = _pd.read_csv(ai_path)
        if len(ai_df) > 0:
            story.append(Paragraph("AI Confidence Scores", h2_style))
            ai_data = [["Organism", "Abundance (%)", "AI Score", "Tier"]]
            for row in ai_df.itertuples():
                ai_data.append([row.organism, f"{row._2:.2f}%", f"{row.ai_score:.1%}", row.tier])
            ai_table = Table(ai_data, colWidths=[3*inch, 1.2*inch, 1.2*inch, 1.1*inch])
            ai_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), bsw_blue),
                ('TEXTCOLOR', (0,0), (-1,0), colors.white),
                ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
                ('FONTSIZE', (0,0), (-1,-1), 9),
                ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
                ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#F5F8FF')]),
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('PADDING', (0,0), (-1,-1), 5),
            ]))
            story.append(ai_table)
            story.append(Spacer(1, 0.15*inch))
    
    # AMR
    amr_path = f"{outdir}/{sample_name}_amr_report.csv"
    if _os.path.exists(amr_path):
        amr_df = _pd.read_csv(amr_path)
        if len(amr_df) > 0:
            story.append(Paragraph("AMR Resistance Genes", h2_style))
            amr_data = [["Gene", "Drug Class", "Coverage", "Identity", "Carrier"]]
            for row in amr_df.itertuples():
                amr_data.append([row.gene, row.drug, f"{row.coverage:.1f}%", f"{row.identity:.1f}%", row.carrier])
            amr_table = Table(amr_data, colWidths=[1.2*inch, 1.5*inch, 1*inch, 1*inch, 1.8*inch])
            amr_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#C00000')),
                ('TEXTCOLOR', (0,0), (-1,0), colors.white),
                ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
                ('FONTSIZE', (0,0), (-1,-1), 9),
                ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
                ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#FFF5F5')]),
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('PADDING', (0,0), (-1,-1), 5),
            ]))
            story.append(amr_table)
            story.append(Spacer(1, 0.15*inch))
        else:
            story.append(Paragraph("AMR Resistance Genes", h2_style))
            story.append(Paragraph("No AMR resistance genes detected", normal))
            story.append(Spacer(1, 0.15*inch))
    
    # Footer
    story.append(HRFlowable(width="100%", thickness=1, color=bsw_blue))
    story.append(Spacer(1, 0.05*inch))
    story.append(Paragraph(
        f"Generated by MAPS Pipeline | Baylor Scott & White Health | {dt.now().strftime('%Y-%m-%d %H:%M')} | "
        f"For clinical decision support only — not a standalone diagnosis",
        ParagraphStyle('Footer', parent=styles['Normal'], fontSize=8, textColor=colors.grey, alignment=TA_CENTER)
    ))
    
    doc.build(story)
    return pdf_path

# ── Login audit log ────────────────────────────────────────────────────
LOG_PATH = _os.path.join(MAPS_HOME, "login_audit.csv")

def log_login(username, success):
    file_exists = _os.path.exists(LOG_PATH)
    with open(LOG_PATH, "a", newline="") as f:
        writer = csv.writer(f)
        if not file_exists:
            writer.writerow(["timestamp", "username", "status"])
        writer.writerow([
            datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            username,
            "SUCCESS" if success else "FAILED"
        ])

