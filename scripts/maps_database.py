#!/usr/bin/env python3
"""
MAPS Database Module - maps_database.py
Step 15 of the MAPS pipeline — saves results to SQLite database.

Database location: /maps/maps_results.db
Schema: see /maps/scripts/maps_database_schema.sql

Key behavior:
  - Reads summary JSON generated by maps_final_report.py (Step 13)
  - Preserves existing SoC (standard of care) data when a sample is rerun
  - SoC data must be manually entered via SQLite after clinical review
  - Do NOT overwrite soc_result and soc_match fields on rerun

To view all results: python3 maps_database.py
To save a result:   python3 maps_database.py save SAMPLE OUTDIR [SOC_RESULT] [SOC_MATCH]
To update SoC:      UPDATE results SET soc_result=X, soc_match=Y WHERE sample=Z

Database columns:
  sample, run_date, quality_flag, human_pct, microbial_reads,
  infection_type, top_organism, top_ai_score, organisms_above_3pct,
  soc_result, soc_match, clinical_summary, timestamp, low_abundance_detections
"""

import sqlite3
import json
import os
import sys
from datetime import datetime

# Path to SQLite database file
# This file stores all validated sample results for concordance tracking
DB_PATH = os.path.expanduser("/maps/maps_results.db")

def init_db():
    """
    Initialize SQLite database and create results table if it does not exist.
    Safe to call multiple times — uses CREATE TABLE IF NOT EXISTS.
    Called automatically before every save or query operation.
    """
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()
    c.execute('''CREATE TABLE IF NOT EXISTS results (
        id              INTEGER PRIMARY KEY AUTOINCREMENT,
        sample          TEXT NOT NULL,
        run_date        TEXT,
        quality_flag    TEXT,
        human_pct       REAL,
        microbial_reads INTEGER,
        infection_type  TEXT,
        top_organism    TEXT,
        top_ai_score    REAL,
        organisms_above_3pct INTEGER,
        soc_result      TEXT,
        soc_match       TEXT,
        clinical_summary TEXT,
        timestamp       TEXT
    )''')
    conn.commit()
    conn.close()

def save_result(sample, outdir, soc_result=None, soc_match=None):
    """
    Save pipeline results for a sample to the database.
    Reads from OUTDIR/SAMPLE_summary.json generated by maps_final_report.py.
    Preserves existing SoC data if sample has been previously validated.
    Deletes old record and inserts new one to reflect latest pipeline run.
    """
    init_db()
    json_path = f"{outdir}/{sample}_summary.json"
    if not os.path.exists(json_path):
        print(f"No summary JSON found for {sample}")
        return
    with open(json_path) as f:
        summary = json.load(f)
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()

    # Check if sample already has validated SoC data in database
    # If so preserve it — never overwrite manually entered clinical validation data
    c.execute("SELECT soc_result, soc_match FROM results WHERE sample=?", (sample,))
    existing = c.fetchone()
    preserved_soc    = existing[0] if existing and existing[0] not in (None, "Unknown") else soc_result or "Unknown"
    preserved_match  = existing[1] if existing and existing[1] not in (None, "Unknown") else soc_match or "Unknown"

    # Delete old record and insert fresh result
    # SoC data preserved in preserved_soc and preserved_match variables above
    c.execute("DELETE FROM results WHERE sample=?", (sample,))
    c.execute('''INSERT INTO results
        (sample, run_date, quality_flag, human_pct, microbial_reads,
         infection_type, top_organism, top_ai_score, organisms_above_3pct,
         soc_result, soc_match, clinical_summary, timestamp)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)''', (
        sample,
        datetime.now().strftime("%Y-%m-%d"),
        summary.get("quality","unknown"),
        summary.get("human_pct",0),
        summary.get("microbial_reads",0),
        summary.get("infection_type","unknown"),
        summary.get("top_organism","None"),
        summary.get("top_ai_score",0),
        summary.get("organisms_above_3pct",0),
        preserved_soc,
        preserved_match,
        summary.get("clinical_summary",""),
        datetime.now().strftime("%Y-%m-%d %H:%M"),
    ))
    conn.commit()
    conn.close()
    print(f"Saved {sample} to database")

def query_all():
    """
    Print all results from database in tabular format.
    Shows sample name, date, quality, top organism, AI score, and SoC match.
    Called when script is run without arguments.
    """
    init_db()
    conn = sqlite3.connect(DB_PATH)
    c    = conn.cursor()
    c.execute('''SELECT sample, run_date, quality_flag, top_organism,
                        top_ai_score, soc_match
                 FROM results ORDER BY timestamp DESC''')
    rows = c.fetchall()
    conn.close()
    print(f"\n{'='*80}")
    print(f"MAPS RESULTS DATABASE — {len(rows)} samples")
    print(f"{'='*80}")
    print(f"{'Sample':<14} {'Date':<12} {'Quality':<10} {'Top Organism':<35} {'AI':>7} {'SoC Match':>10}")
    print("─"*80)
    for row in rows:
        sample, date, qual, top_org, top_ai, match = row
        org_short = (top_org or "None")[:33]
        print(f"{sample:<14} {date:<12} {qual:<10} {org_short:<35} "
              f"{(top_ai or 0)*100:>6.1f}% {match or 'Unknown':>10}")

if __name__ == "__main__":
    # CLI usage:
    # python3 maps_database.py          — show all results
    # python3 maps_database.py save SAMPLE OUTDIR — save result
    # python3 maps_database.py save SAMPLE OUTDIR SOC SOC_MATCH — save with SoC
    init_db()
    if len(sys.argv) >= 3 and sys.argv[1] == "save":
        save_result(sys.argv[2], sys.argv[3],
                   sys.argv[4] if len(sys.argv) > 4 else None,
                   sys.argv[5] if len(sys.argv) > 5 else None)
    else:
        query_all()
